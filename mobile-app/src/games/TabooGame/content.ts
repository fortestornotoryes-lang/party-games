export const TABOO_CLASSIC_CARDS: readonly TabooClassicCard[] = [...EASY, ...MEDIUM, ...HARD];

export function getDuplicateWords(cards: TabooClassicCard[]): string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();

  for (const card of cards) {
    const normalizedWord = card.word.trim().toUpperCase();
    if (seen.has(normalizedWord)) {
      duplicates.add(normalizedWord);
    } else {
      seen.add(normalizedWord);
    }
  }

  return Array.from(duplicates);
}

