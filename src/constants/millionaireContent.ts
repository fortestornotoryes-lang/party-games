export const simulateAudienceVote = (correctIndex: number): number[] => {
  const votes = [0, 0, 0, 0];
  const correctVotes = 45 + Math.floor(Math.random() * 31);
  votes[correctIndex] = correctVotes;
  const wrongIndices = [0, 1, 2, 3].filter((i) => i !== correctIndex);
  let remaining = 100 - correctVotes;
  for (let i = 0; i < wrongIndices.length - 1; i++) {
    const maxShare = remaining - (wrongIndices.length - 1 - i);
    const share = Math.floor(Math.random() * (maxShare + 1));
    votes[wrongIndices[i]] = share;
    remaining -= share;
  }
  votes[wrongIndices[wrongIndices.length - 1]] = remaining;
  return votes;
};
